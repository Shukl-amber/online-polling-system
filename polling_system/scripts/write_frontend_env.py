#!/usr/bin/env python3
"""Script to read deployment parameters from SSM Parameter Store and generate frontend/.env.

Reads the following parameters published by the CloudFormation/SAM stacks:
- /polling_system/auth/user_pool_id
- /polling_system/auth/browser_client_id
- /polling_system/api/base_url
- /polling_system/hosting/cloudfront_domain (optional)

Usage:
    python scripts/write_frontend_env.py [--region ap-south-1]
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import boto3
from botocore.exceptions import ClientError


def get_ssm_parameter(ssm_client: boto3.client, name: str) -> str | None:
    """Fetch a parameter from SSM Parameter Store, returning None if not found."""
    try:
        response = ssm_client.get_parameter(Name=name, WithDecryption=False)
        return response["Parameter"]["Value"]
    except ClientError as exc:
        if exc.response["Error"]["Code"] == "ParameterNotFound":
            return None
        raise


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Generate frontend/.env from deployed SSM parameters"
    )
    parser.add_argument(
        "--region",
        default="ap-south-1",
        help="AWS region (default: ap-south-1)",
    )
    parser.add_argument(
        "--api-url",
        help="Override API base URL directly",
    )
    parser.add_argument(
        "--user-pool-id",
        help="Override Cognito User Pool ID directly",
    )
    parser.add_argument(
        "--client-id",
        help="Override Cognito Browser App Client ID directly",
    )
    args = parser.parse_args()

    region = args.region
    ssm = boto3.client("ssm", region_name=region)

    print(f"Reading parameters from SSM Parameter Store (region: {region})...")

    def get_fallback(*names: str) -> str | None:
        for n in names:
            val = get_ssm_parameter(ssm, n)
            if val:
                return val
        return None

    user_pool_id = args.user_pool_id or get_fallback(
        "/polling_system/user_pool_id",
        "/polling_system/auth/user_pool_id",
    )
    client_id = args.client_id or get_fallback(
        "/polling_system/browser_client_id",
        "/polling_system/auth/browser_client_id",
    )
    api_url = args.api_url or get_fallback(
        "/polling_system/api_url",
        "/polling_system/api/base_url",
    )
    cloudfront_domain = get_fallback(
        "/polling_system/cloudfront_domain",
        "/polling_system/hosting/cloudfront_domain",
    )

    missing = []
    if not user_pool_id:
        missing.append("/polling_system/auth/user_pool_id")
    if not client_id:
        missing.append("/polling_system/auth/browser_client_id")
    if not api_url:
        missing.append("/polling_system/api/base_url")

    if missing:
        print(
            f"Error: Missing required SSM parameters: {', '.join(missing)}\n"
            "Ensure stacks 01_auth, 03_hosting, and 04_api are deployed.",
            file=sys.stderr,
        )
        sys.exit(1)

    # Format values
    if api_url and api_url.endswith("/"):
        api_url = api_url[:-1]

    env_content = f"""# Auto-generated by scripts/write_frontend_env.py
VITE_API_URL={api_url}
VITE_AWS_REGION={region}
VITE_USER_POOL_ID={user_pool_id}
VITE_USER_POOL_CLIENT_ID={client_id}
"""
    if cloudfront_domain:
        env_content += f"VITE_CLOUDFRONT_DOMAIN={cloudfront_domain}\n"

    repo_root = Path(__file__).resolve().parent.parent
    env_path = repo_root / "frontend" / ".env"
    env_path.write_text(env_content, encoding="utf-8")

    print(f"Successfully generated {env_path}")
    print(f"  VITE_API_URL: {api_url}")
    print(f"  VITE_AWS_REGION: {region}")
    print(f"  VITE_USER_POOL_ID: {user_pool_id}")
    print(f"  VITE_USER_POOL_CLIENT_ID: {client_id}")


if __name__ == "__main__":
    main()
